import type { FieldCompare, InterfaceLink, InterfaceRecord, RecordMatchStatus, SiteCode } from '@/lib/types'
import { minutesAgo, plusMinutes } from '@/lib/clock'

function fc(
  label: string,
  sourceValue: string,
  targetValue: string,
  opts?: { match?: boolean; note?: string },
): FieldCompare {
  return {
    name: label.toLowerCase().replace(/[^a-z0-9]+/g, '_'),
    label,
    sourceValue,
    targetValue,
    match: opts?.match ?? sourceValue === targetValue,
    note: opts?.note,
  }
}

interface RecInput {
  id: string
  interfaceId: string
  key: string
  reference: string
  status: RecordMatchStatus
  site: SiteCode
  sentMinutesAgo: number
  latencyMinutes?: number
  vehicle?: string
  messageId: string
  fields: FieldCompare[]
  findingId?: string
}

function rec(input: RecInput): InterfaceRecord {
  const sentAt = minutesAgo(input.sentMinutesAgo)
  return {
    id: input.id,
    interfaceId: input.interfaceId,
    key: input.key,
    reference: input.reference,
    vehicle: input.vehicle,
    site: input.site,
    sentAt,
    receivedAt:
      input.status === 'Missing' ? undefined : plusMinutes(sentAt, input.latencyMinutes ?? 2),
    status: input.status,
    messageId: input.messageId,
    fields: input.fields,
    findingId: input.findingId,
  }
}

